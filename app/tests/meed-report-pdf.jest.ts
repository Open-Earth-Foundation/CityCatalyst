beforeAll(() => {
  const png = readFileSync("public/assets/citycatalyst-logo-blue.png");
  (global as any).fetch = async () => ({
    ok: true,
    blob: async () => ({ __png: png }),
  });
  (global as any).FileReader = class {
    onloadend: (() => void) | null = null;
    onerror: (() => void) | null = null;
    result = "";
    readAsDataURL(blob: any) {
      this.result = `data:image/png;base64,${Buffer.from(blob.__png).toString("base64")}`;
      this.onloadend?.();
    }
  };
});

