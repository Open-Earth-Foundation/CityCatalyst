const render = async (documents = [document]) => {
  const pdf = await buildReportPdf(documents, meta);
  return {
    pdf,
    bytes: Buffer.from(pdf.output("arraybuffer")),
  };
};

// End-to-end over the real chapter shapes the prompts emit. The layout itself
// cannot be asserted, but the things that were actually broken can be.
describe("report pdf", () => {
  it("renders multi-page content without throwing", async () => {
    const { pdf } = await render();
    expect(pdf.getNumberOfPages()).toBeGreaterThan(1);
  });

  it("turns table cell links into real PDF annotations", async () => {
    const { bytes } = await render();
    const uris = bytes.toString("latin1").match(/\/URI/g) ?? [];
    // "Programme page" wraps, so each link contributes more than one rect.
    expect(uris.length).toBeGreaterThanOrEqual(3);
    expect(bytes.toString("latin1")).toContain("https://energia.gob.cl/a");
  });

  it("stays small enough to email, despite embedding the logo", async () => {
    const { bytes } = await render();
    // Uncompressed, the raw logo bitmap alone is ~850 KB.
    expect(bytes.length).toBeLessThan(200_000);
  });

  it("gives each action its own page", async () => {
    const one = await render();
    const two = await render([
      document,
      { ...document, actionId: "icare_0027" },
    ]);
    expect(two.pdf.getNumberOfPages()).toBeGreaterThan(
      one.pdf.getNumberOfPages(),
    );
  });

  it("survives a document with no sections", async () => {
    const { pdf } = await render([
      { actionId: "x", actionName: "Empty action", sections: [] },
    ]);
    expect(pdf.getNumberOfPages()).toBe(1);
  });
});
